def lookup_shelf_life(name: str, category: str) -> tuple[int, int]:
    """查询已验证的保鲜期范围。先按精确食材名查,再按品类fallback。"""
    # 精确匹配
    if (name, category) in VERIFIED_SHELF_LIFE:
        return VERIFIED_SHELF_LIFE[(name, category)]
    # 品类fallback
    if (category, category) in VERIFIED_SHELF_LIFE:
        return VERIFIED_SHELF_LIFE[(category, category)]
    # 最终默认
    return (3, 7)

